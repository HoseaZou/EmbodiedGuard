"""Read-only remaining-path checks of measured static objects.

Routes generated by this executor have strictly increasing world x. Trimming
uses that invariant and the measured pose, not controller cursor mutation or
simulator truth. Moving objects keep their original per-action safety checks.
"""
from bisect import bisect_right
from .planning import blocked_by


def static_obstacle_signature(obstacles):
    return tuple(sorted((obj['id'], obj['x'], obj['y'], obj['radius'])
        for obj in obstacles if obj['vx'] == 0 and obj['vy'] == 0))


def remaining_path(points, pose):
    if len(points) < 2 or any(b[0] <= a[0] for a,b in zip(points,points[1:])):
        raise ValueError('Remaining-path check requires an ordered forward route')
    index = min(max(bisect_right([point[0] for point in points],pose.x)-1,0),len(points)-2)
    return [(pose.x,pose.y),*points[index+1:]]


def observed_remaining_blockers(points, pose, obstacles, config):
    return blocked_by(remaining_path(points,pose),obstacles,config)
